using System.Collections;
using Newtonsoft.Json.Linq;

namespace ImSharpGenerator;

internal class EnumDefinition : ISourceGenerator, IEnumerable<EnumDefinition.EnumValue>
{
    private static readonly Dictionary<string, string> ImGuizmoEnumRenames = new()
    {
        ["COLOR"] = "ImGuizmoColor",
        ["MODE"] = "ImGuizmoMode",
        ["MOVETYPE"] = "ImGuizmoMoveType",
        ["OPERATION"] = "ImGuizmoOperation",
    };

    public bool Flags { get; }
    public string Name { get; }
    public string FriendlyName { get; }
    public string UnderlyingType { get; }
    public LibraryDescriptor Library { get; }
    public List<EnumValue> Values { get; } = [];

    public EnumDefinition(JProperty enumJson, LibraryDescriptor library, string? underlyingCSharpType = null)
    {
        Name = enumJson.Name;
        Library = library;
        FriendlyName = ComputeFriendlyName(Name, library);
        Flags = Name.Contains("Flags") || Name == "OPERATION";
        UnderlyingType = underlyingCSharpType ?? "int";

        var seenNames = new HashSet<string>(StringComparer.Ordinal);
        if (enumJson.Value is JArray arr)
        {
            foreach (var field in arr)
            {
                var name = field["name"]?.ToString();
                var value = field["value"]?.ToString();
                var calcValue = field["calc_value"]?.ToString();
                if (name == null || calcValue == null)
                    continue;

                if (!long.TryParse(calcValue, out long parsedVal))
                    continue;

                var enumVal = new EnumValue(Name, name, value ?? calcValue, parsedVal);
                if (seenNames.Add(enumVal.FriendlyName))
                {
                    Values.Add(enumVal);
                }
            }
        }
    }

    private static string ComputeFriendlyName(string rawName, LibraryDescriptor library)
    {
        if (library.Id.Equals("cimguizmo", StringComparison.OrdinalIgnoreCase) &&
            ImGuizmoEnumRenames.TryGetValue(rawName, out var renamed))
        {
            return renamed;
        }

        return IdentifierHelper.EscapeIdentifier(rawName.TrimEnd('_'));
    }

    public string GenerateSource()
    {
        using var writer = new CSharpWriter();
        writer.WriteAutoGeneratedHeader();

        writer.WriteLineIndented("using System;");
        writer.WriteLine();
        writer.WriteLineIndented($"namespace {Library.Namespace};");
        writer.WriteLine();

        if (Flags)
        {
            writer.WriteLineIndented("[Flags]");
        }

        string typeSuffix = UnderlyingType == "int" ? "" : $" : {UnderlyingType}";
        writer.WriteLineIndented($"public enum {FriendlyName}{typeSuffix}");
        using (writer.WriteBlock())
        {
            foreach (var value in Values)
            {
                string formattedVal = FormatValue(value.CalculatedValue);
                writer.WriteLineIndented($"{value.FriendlyName} = {formattedVal},");
            }
        }

        return writer.ToString();
    }

    private string FormatValue(long val)
    {
        if (UnderlyingType == "int")
        {
            if (val > int.MaxValue)
                return $"unchecked((int)0x{val:X})";
            if (Flags && val > 0 && (val & (val - 1)) == 0 && val <= (1L << 30))
            {
                int bit = 0;
                long tmp = val;
                while (tmp > 1) { tmp >>= 1; bit++; }
                return $"1 << {bit}";
            }
            return val.ToString();
        }

        if (UnderlyingType == "uint")
            return $"0x{val:X}u";

        return val.ToString();
    }

    public IEnumerator<EnumValue> GetEnumerator() => Values.GetEnumerator();
    IEnumerator IEnumerable.GetEnumerator() => GetEnumerator();

    public class EnumValue
    {
        public string Name { get; }
        public string FriendlyName { get; }
        public string RawValue { get; }
        public long CalculatedValue { get; }

        public EnumValue(string enumName, string name, string rawValue, long calculatedValue)
        {
            Name = name;
            RawValue = rawValue;
            CalculatedValue = calculatedValue;

            string prefixWithUnderscore = enumName.EndsWith("_", StringComparison.Ordinal) ? enumName : enumName + "_";
            string friendly = name;
            if (friendly.StartsWith(prefixWithUnderscore, StringComparison.Ordinal))
            {
                friendly = friendly.Substring(prefixWithUnderscore.Length);
            }
            else if (friendly.StartsWith(enumName, StringComparison.Ordinal) && friendly.Length > enumName.Length)
            {
                friendly = friendly.Substring(enumName.Length).TrimStart('_');
            }

            FriendlyName = IdentifierHelper.EscapeIdentifier(friendly);
        }
    }
}
