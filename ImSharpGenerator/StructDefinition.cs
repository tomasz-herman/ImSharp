    public StructDefinition(JProperty structJson, LibraryDescriptor library)
    {
        NativeName = structJson.Name;
        Library = library;
        FriendlyName = (library.Id.Equals("cimguizmo", StringComparison.OrdinalIgnoreCase) && NativeName == "Style")
            ? "ImGuizmoStyle"
            : IdentifierHelper.EscapeIdentifier(NativeName);

        if (structJson.Value is JArray arr)
        {
            foreach (var field in arr)
            {
                var name = field["name"]?.ToString() ?? "";
                var type = field["type"]?.ToString();
                var size = field["size"]?.ToObject<int>() ?? -1;
                var template = field["template_type"]?.ToString();
                var bitfieldStr = field["bitfield"]?.ToString();
                int bitfieldWidth = int.TryParse(bitfieldStr, out int bw) ? bw : 0;

                if (type != null)
                {
                    // Handle rare cimgui parser split of complex array-size expressions like:
                    // type: "ImVec4 TexUvLines[(32)+1+(((4)-", name: "1)*(4)+1)]"
                    if (!type.StartsWith("union", StringComparison.Ordinal) &&
                        !type.Contains("(*") &&
                        type.Contains("[") &&
                        name.EndsWith("]", StringComparison.Ordinal))
                    {
                        string combined = type + name;
                        int bracketStart = combined.IndexOf('[');
                        int bracketEnd = combined.LastIndexOf(']');
                        if (bracketStart > 0 && bracketEnd > bracketStart)
                        {
                            string beforeBracket = combined.Substring(0, bracketStart).Trim();
                            string expr = combined.Substring(bracketStart + 1, bracketEnd - bracketStart - 1);
                            int lastSpace = beforeBracket.LastIndexOf(' ');
                            if (lastSpace > 0)
                            {
                                type = beforeBracket.Substring(0, lastSpace).Trim();
                                name = beforeBracket.Substring(lastSpace + 1).Trim();
                                if (TryEvaluateIntExpression(expr, out int evaluatedSize) && evaluatedSize > 0)
                                {
                                    size = evaluatedSize;
                                }
                            }
                        }
                    }

                    Fields.Add(new StructField(name, type, size, template, bitfieldWidth));
                }
            }
        }
    }

