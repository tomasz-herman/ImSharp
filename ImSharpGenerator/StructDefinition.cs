                                writer.WriteLineIndented($"readonly get => ({propType})(({backingFieldName} >> {bf.Shift}) & {maskLiteral});");
                                writer.WriteLineIndented($"set => {backingFieldName} = ({unsignedBacking})(({backingFieldName} & ~({maskLiteral} << {bf.Shift})) | (((({unsignedBacking})value) & {maskLiteral}) << {bf.Shift}));");
