                        nestedTypes.Add(BuildInlineArrayStruct(arrayStructName, elemType, field.Size));
                        writer.WriteLineIndented($"public {arrayStructName} {fieldName};");
                    }
                }
                else
                {
                    writer.WriteLineIndented($"public {resolvedType} {fieldName};");
                }

                i++;
            }

            if (nestedTypes.Count > 0)
            {
                writer.WriteLine();
                foreach (var nested in nestedTypes)
                {
                    foreach (var line in nested.Split('\n'))
                    {
                        if (line.Length == 0)
                            writer.WriteLine();
                        else
                            writer.WriteLineIndented(line.TrimEnd('\r'));
                    }
                }
            }
        }

        // Emit safe pointer wrapper struct (e.g. ImGuiIOPtr, ImDrawDataPtr, TextEditorPtr)
        if (!FriendlyName.EndsWith("Ptr", StringComparison.Ordinal))
        {
            writer.WriteLine();
            EmitSafePtrStruct(writer, FriendlyName, Fields, typesInfo, Library);
        }

        return writer.ToString();
    }

    internal static void EmitSafePtrStruct(
        CSharpWriter writer,
        string structName,
        List<StructField>? fields,
        TypesInfo? typesInfo,
        LibraryDescriptor? library)
    {
        string ptrName = $"{structName}Ptr";
        writer.WriteLineIndented($"public readonly partial struct {ptrName} : IEquatable<{ptrName}>");
        using (writer.WriteBlock())
        {
            writer.WriteLineIndented("public nint Handle { get; }");
            writer.WriteLine();
            writer.WriteLineIndented($"public {ptrName}(nint handle) => Handle = handle;");
            writer.WriteLineIndented($"public unsafe {ptrName}({structName}* handle) => Handle = (nint)handle;");
            writer.WriteLine();
            writer.WriteLineIndented("public bool IsNull => Handle == 0;");
            writer.WriteLineIndented($"public static {ptrName} Null => default;");
            writer.WriteLine();
            writer.WriteLineIndented($"public unsafe {structName}* NativePtr => ({structName}*)Handle;");
            writer.WriteLine();
            writer.WriteLineIndented($"public ref {structName} AsRef() {{ unsafe {{ return ref Unsafe.AsRef<{structName}>((void*)Handle); }} }}");
            writer.WriteLine();
            writer.WriteLineIndented($"public static unsafe implicit operator {ptrName}({structName}* ptr) => new((nint)ptr);");
            writer.WriteLineIndented($"public static unsafe implicit operator {structName}*({ptrName} ptr) => ({structName}*)ptr.Handle;");
            writer.WriteLine();
            writer.WriteLineIndented($"public bool Equals({ptrName} other) => Handle == other.Handle;");
            writer.WriteLineIndented($"public override bool Equals(object? obj) => obj is {ptrName} other && Equals(other);");
            writer.WriteLineIndented("public override int GetHashCode() => Handle.GetHashCode();");
            writer.WriteLineIndented($"public static bool operator ==({ptrName} left, {ptrName} right) => left.Handle == right.Handle;");
            writer.WriteLineIndented($"public static bool operator !=({ptrName} left, {ptrName} right) => left.Handle != right.Handle;");

            // Emit safe property accessors for regular fields on defined structs
            if (fields != null && typesInfo != null && library != null)
            {
                var usedPropNames = new HashSet<string>(StringComparer.Ordinal)
                {
                    "Handle", "IsNull", "Null", "NativePtr", "AsRef", "Equals", "GetHashCode", "ToString"
                };

                foreach (var field in fields)
                {
                    if (field.Type.StartsWith("union", StringComparison.Ordinal) || field.BitfieldWidth > 0)
                        continue;

                    string fieldName = IdentifierHelper.EscapeIdentifier(field.Name);
                    if (!usedPropNames.Add(fieldName))
                        continue;

                    string resolvedType = typesInfo.ResolveType(field.Type, library);

                    // Skip fixed primitive arrays and pointer arrays
                    if (field.Size > 0)
                        continue;

                    if (!resolvedType.Contains("*"))
                    {
                        if (field.Type.Trim() == "bool" && resolvedType == "byte")
                        {
                            writer.WriteLineIndented($"public bool {fieldName} {{ get {{ unsafe {{ return (({structName}*)Handle)->{fieldName} != 0; }} }} set {{ unsafe {{ (({structName}*)Handle)->{fieldName} = value ? (byte)1 : (byte)0; }} }} }}");
                        }
                        else
                        {
                            writer.WriteLineIndented($"public ref {resolvedType} {fieldName} {{ get {{ unsafe {{ return ref (({structName}*)Handle)->{fieldName}; }} }} }}");
                        }
                    }
                    else if (resolvedType.EndsWith("*", StringComparison.Ordinal) &&
                             !resolvedType.EndsWith("**", StringComparison.Ordinal))
                    {
                        string target = resolvedType.Substring(0, resolvedType.Length - 1);
                        if (typesInfo.IsStruct(target, library) && !target.EndsWith("Ptr", StringComparison.Ordinal))
                        {
                            string targetPtr = $"{target}Ptr";
                            writer.WriteLineIndented($"public {targetPtr} {fieldName} {{ get {{ unsafe {{ return new((({structName}*)Handle)->{fieldName}); }} }} set {{ unsafe {{ (({structName}*)Handle)->{fieldName} = value; }} }} }}");
                        }
                    }
                }
            }
        }
    }

    private static string BuildInlineArrayStruct(string structName, string elementType, int length)
    {
        return
            $"[InlineArray({length})]\n" +
            $"public struct {structName}\n" +
            "{\n" +
            $"    private {elementType} _element0;\n" +
            "}\n";
    }

    private static void EmitUnionNestedStruct(List<string> nestedTypes, string unionTypeName, string rawUnion, TypesInfo typesInfo, LibraryDescriptor library)
    {
        var match = UnionBodyRegex.Match(rawUnion);
        if (!match.Success)
            return;

        string body = match.Groups[1].Value;
        var members = body.Split([';'], StringSplitOptions.RemoveEmptyEntries);

        using var uw = new CSharpWriter();
        uw.WriteLineIndented("[StructLayout(LayoutKind.Explicit)]");
        uw.WriteLineIndented($"public unsafe struct {unionTypeName}");
        using (uw.WriteBlock())
        {
            foreach (var rawMember in members)
            {
                string trimmed = rawMember.Trim();
                if (string.IsNullOrEmpty(trimmed))
                    continue;

                // Parse e.g. "int BackupInt[2]" or "void* val_p" or "ImGuiInputEventMousePos MousePos"
                int lastSpace = trimmed.LastIndexOf(' ');
                if (lastSpace <= 0)
                    continue;

                string memberTypeRaw = trimmed.Substring(0, lastSpace).Trim();
                string memberNameRaw = trimmed.Substring(lastSpace + 1).Trim();

                // Check for array suffix on member name, e.g. BackupInt[2]
                int arraySize = -1;
                int bracketStart = memberNameRaw.IndexOf('[');
                if (bracketStart > 0)
                {
                    int bracketEnd = memberNameRaw.IndexOf(']', bracketStart);
                    if (bracketEnd > bracketStart)
                    {
                        string sizeText = memberNameRaw.Substring(bracketStart + 1, bracketEnd - bracketStart - 1);
                        int.TryParse(sizeText, out arraySize);
                    }
                    memberNameRaw = memberNameRaw.Substring(0, bracketStart);
                }

                // Move leading '*' from name to type if present
                while (memberNameRaw.StartsWith("*", StringComparison.Ordinal))
                {
                    memberTypeRaw += "*";
                    memberNameRaw = memberNameRaw.Substring(1);
                }

                string memberName = IdentifierHelper.EscapeIdentifier(memberNameRaw);
                string resolved = typesInfo.ResolveType(memberTypeRaw, library);

                uw.WriteLineIndented("[FieldOffset(0)]");
                if (arraySize > 0 && TypesInfo.IsFixedBufferPrimitive(resolved))
                {
                    uw.WriteLineIndented($"public fixed {resolved} {memberName}[{arraySize}];");
                }
                else
                {
                    uw.WriteLineIndented($"public {resolved} {memberName};");
                }
            }
        }

        nestedTypes.Add(uw.ToString());
    }

    private static int GetBitWidth(string csharpType) => csharpType switch
    {
        "byte" or "sbyte" or "bool" => 8,
        "short" or "ushort" => 16,
        "int" or "uint" => 32,
        "long" or "ulong" => 64,
        _ => 32
    };

    private static string GetUnsignedType(int bits) => bits switch
    {
        8 => "byte",
        16 => "ushort",
        32 => "uint",
        64 => "ulong",
        _ => "uint"
    };

    private static bool TryEvaluateIntExpression(string expr, out int result)
    {
        int pos = 0;
        result = 0;
        if (!TryParseAddSub(expr, ref pos, out result))
            return false;
        SkipWhitespace(expr, ref pos);
        return pos == expr.Length;
    }

    private static void SkipWhitespace(string s, ref int pos)
    {
        while (pos < s.Length && char.IsWhiteSpace(s[pos])) pos++;
    }

    private static bool TryParseAddSub(string s, ref int pos, out int value)
    {
        if (!TryParseMulDiv(s, ref pos, out value)) return false;
        while (true)
        {
            SkipWhitespace(s, ref pos);
            if (pos >= s.Length) break;
            char op = s[pos];
            if (op != '+' && op != '-') break;
            pos++;
            if (!TryParseMulDiv(s, ref pos, out int rhs)) return false;
            value = op == '+' ? value + rhs : value - rhs;
        }
        return true;
    }

    private static bool TryParseMulDiv(string s, ref int pos, out int value)
    {
        if (!TryParsePrimary(s, ref pos, out value)) return false;
        while (true)
        {
            SkipWhitespace(s, ref pos);
            if (pos >= s.Length) break;
            char op = s[pos];
            if (op != '*' && op != '/') break;
            pos++;
            if (!TryParsePrimary(s, ref pos, out int rhs)) return false;
            if (op == '/' && rhs == 0) return false;
            value = op == '*' ? value * rhs : value / rhs;
        }
        return true;
    }

    private static bool TryParsePrimary(string s, ref int pos, out int value)
    {
        value = 0;
        SkipWhitespace(s, ref pos);
        if (pos >= s.Length) return false;

        if (s[pos] == '(')
        {
            pos++;
            if (!TryParseAddSub(s, ref pos, out value)) return false;
            SkipWhitespace(s, ref pos);
            if (pos >= s.Length || s[pos] != ')') return false;
            pos++;
            return true;
        }

        if (s[pos] == '-')
        {
            pos++;
            if (!TryParsePrimary(s, ref pos, out int inner)) return false;
            value = -inner;
            return true;
        }

        int start = pos;
        while (pos < s.Length && char.IsDigit(s[pos])) pos++;
        if (pos == start) return false;
        return int.TryParse(s.Substring(start, pos - start), out value);
    }

