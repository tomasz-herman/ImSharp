    public static string GenerateNativeClass(LibraryDescriptor library, List<FunctionDefinition> functions, TypesInfo typesInfo)
    {
        string className = library.NativeClassName;

        using var writer = new CSharpWriter();
        writer.WriteAutoGeneratedHeader();

        writer.WriteLineIndented("using System;");
        writer.WriteLineIndented("using System.Runtime.InteropServices;");
        if (!library.IsCoreNamespace)
            writer.WriteLineIndented("using ImSharp;");
        writer.WriteLine();
        writer.WriteLineIndented($"namespace {library.Namespace};");
        writer.WriteLine();
        writer.WriteLineIndented($"public static unsafe partial class {className}");
        using (writer.WriteBlock())
        {
            writer.WriteLineIndented("private const string LibraryName = \"ImSharpNative\";");
            writer.WriteLine();

            var emittedEntryPoints = new HashSet<string>(StringComparer.Ordinal);

            foreach (var fn in functions)
            {
                if (fn.ShouldSkipNative)
                    continue;

                if (!emittedEntryPoints.Add(fn.EntryPoint))
                    continue;

                string retType = typesInfo.ResolveType(fn.RawReturnType, library);

                var paramDecls = new List<string>(fn.Parameters.Count);
                var usedNames = new HashSet<string>(StringComparer.Ordinal);

                for (int i = 0; i < fn.Parameters.Count; i++)
                {
                    var p = fn.Parameters[i];
                    string pType = typesInfo.ResolveType(p.RawType, library);
                    if (pType == "void") pType = "nint";

                    string pName = IdentifierHelper.EscapeIdentifier(
                        string.IsNullOrWhiteSpace(p.RawName) ? $"arg{i}" : p.RawName);

                    while (!usedNames.Add(pName))
                        pName += "_";

                    paramDecls.Add($"{pType} {pName}");
                }

                writer.WriteLineIndented($"[DllImport(LibraryName, EntryPoint = \"{fn.EntryPoint}\", CallingConvention = CallingConvention.Cdecl, ExactSpelling = true)]");
                writer.WriteLineIndented($"public static extern {retType} {fn.EntryPoint}({string.Join(", ", paramDecls)});");
                writer.WriteLine();
            }
        }

        return writer.ToString();
    }

    public static string GenerateWrapperClass(LibraryDescriptor library, List<FunctionDefinition> functions, TypesInfo typesInfo)
    {
        string className = library.ClassName;
        string nativeClass = library.NativeClassName;

        using var writer = new CSharpWriter();
        writer.WriteAutoGeneratedHeader();

        writer.WriteLineIndented("using System;");
        writer.WriteLineIndented("using System.Numerics;");
        writer.WriteLineIndented("using System.Runtime.CompilerServices;");
        if (!library.IsCoreNamespace)
            writer.WriteLineIndented("using ImSharp;");
        writer.WriteLine();
        writer.WriteLineIndented($"namespace {library.Namespace};");
        writer.WriteLine();
        writer.WriteLineIndented($"public static partial class {className}");
        using (writer.WriteBlock())
        {
            var emittedSignatures = new HashSet<string>(StringComparer.Ordinal);
            bool isCte = library.Id.Equals("cimcte", StringComparison.OrdinalIgnoreCase);
            bool isNodesR = library.Id.Equals("cimnodes_r", StringComparison.OrdinalIgnoreCase);

            foreach (var fn in functions)
            {
                if (fn.ShouldSkipNative || fn.IsInternal)
                    continue;

                bool isGlobal = string.IsNullOrEmpty(fn.StructName);
                bool isCteMethod = isCte && fn.StructName == "TextEditor";
                bool isNodesRCanvasCtorDtor = isNodesR && fn.StructName == "CanvasState" && (fn.IsConstructor || fn.IsDestructor);

                if (!isGlobal && !isCteMethod && !isNodesRCanvasCtorDtor)
                    continue;

                string methodName = ComputeWrapperMethodName(fn, library);
                if (string.IsNullOrEmpty(methodName))
                    continue;

                bool hasOptBoolPtr = HasOptionalBoolPtr(fn);

                // 1. Primary safe API overload (omit optional bool* = NULL here so callers get clean Begin(name, flags) without ambiguity)
                EmitWrapperMethod(writer, nativeClass, methodName, fn, library, typesInfo, PointerStrategy.SafeSpan, omitNullBoolPtr: hasOptBoolPtr, emittedSignatures);

                // 2. Emit `ref T` overload for mutable scalar/vec/quat/bool pointers
                //    (e.g. Checkbox("Check", ref b), SliderFloat("Val", ref f, 0, 1), Begin("Win", ref open), gizmo3D("##q", ref q, ...))
                if (HasRefFriendlyParameters(fn, library, typesInfo))
                {
                    EmitWrapperMethod(writer, nativeClass, methodName, fn, library, typesInfo, PointerStrategy.SafeRef, omitNullBoolPtr: false, emittedSignatures);
                }
            }
        }

        return writer.ToString();
    }

    private static string ComputeWrapperMethodName(FunctionDefinition fn, LibraryDescriptor library)
    {
        if (library.Id.Equals("cimcte", StringComparison.OrdinalIgnoreCase) && fn.StructName == "TextEditor")
        {
            if (fn.IsConstructor) return "Create";
            if (fn.IsDestructor) return "Destroy";
        }

        if (library.Id.Equals("cimnodes_r", StringComparison.OrdinalIgnoreCase) && fn.StructName == "CanvasState")
        {
            if (fn.IsConstructor) return "CreateCanvasState";
            if (fn.IsDestructor) return "DestroyCanvasState";
        }

        string name = fn.FuncName;
        if (string.IsNullOrEmpty(name))
        {
            name = fn.EntryPoint;
            if (!string.IsNullOrEmpty(library.PrefixStrip) && name.StartsWith(library.PrefixStrip, StringComparison.Ordinal))
                name = name.Substring(library.PrefixStrip.Length);
        }

        if (fn.EntryPoint.EndsWith("0", StringComparison.Ordinal) && name.EndsWith("0", StringComparison.Ordinal) && name.Length > 1)
        {
            name = name.Substring(0, name.Length - 1);
        }

        return IdentifierHelper.EscapeIdentifier(name);
    }

    private static bool IsConstCharPtr(string rawType)
    {
        string t = rawType.Trim();
        return t == "const char*" || t == "const char *";
    }

    private static bool IsVoidPtr(string rawType, string nativeType)
    {
        if (nativeType != "void*") return false;
        string t = rawType.Trim();
        return t is "void*" or "const void*" or "void *" or "const void *";
    }

    private static bool IsBoolReturn(string rawType) => rawType.Trim() == "bool";

    private static bool IsBoolParam(string rawType) => rawType.Trim() == "bool";

    private static bool IsConstPointer(string rawType)
    {
        string t = rawType.Trim();
        return t.StartsWith("const ", StringComparison.Ordinal);
    }

    private static bool IsOptionalNullDefault(FunctionDefinition fn, string rawName) =>
        fn.Defaults.TryGetValue(rawName, out var def) && (def == "NULL" || def == "nullptr" || def == "0");

    private static bool HasOptionalBoolPtr(FunctionDefinition fn) =>
        fn.Parameters.Any(p => p.RawType.Trim() == "bool*" && IsOptionalNullDefault(fn, p.RawName));

    private static bool TryGetSingleStructPointerTarget(string nativeType, LibraryDescriptor library, TypesInfo typesInfo, out string structName)
    {
        structName = "";
        if (!nativeType.EndsWith("*", StringComparison.Ordinal) || nativeType.EndsWith("**", StringComparison.Ordinal))
            return false;

        string target = nativeType.Substring(0, nativeType.Length - 1);
        if (typesInfo.IsStruct(target, library) && !target.EndsWith("Ptr", StringComparison.Ordinal))
        {
            structName = target;
            return true;
        }
        return false;
    }

    private static bool TryGetSpanElementType(string nativeType, out string elemType)
    {
        elemType = "";
        if (!nativeType.EndsWith("*", StringComparison.Ordinal) || nativeType.EndsWith("**", StringComparison.Ordinal))
            return false;

        string target = nativeType.Substring(0, nativeType.Length - 1);
        if (SpanFriendlyElementTypes.Contains(target))
        {
            elemType = target;
            return true;
        }
        return false;
    }

    private static bool IsRefFriendlyParam(string rawType, string resolvedNativeType)
    {
        if (IsConstPointer(rawType))
            return false;

        string t = rawType.Trim();
        if (t == "bool*")
            return true;

        if (!resolvedNativeType.EndsWith("*", StringComparison.Ordinal) || resolvedNativeType.EndsWith("**", StringComparison.Ordinal))
            return false;

        string elem = resolvedNativeType.Substring(0, resolvedNativeType.Length - 1);
        return elem is "float" or "double" or "int" or "uint" or "ImVec2" or "ImVec4"
            or "System.Numerics.Vector3" or "System.Numerics.Vector4" or "System.Numerics.Quaternion";
    }

    private static bool HasRefFriendlyParameters(FunctionDefinition fn, LibraryDescriptor library, TypesInfo typesInfo)
    {
        int count = 0;
        foreach (var p in fn.Parameters)
        {
            string resolved = typesInfo.ResolveType(p.RawType, library);
            if (IsRefFriendlyParam(p.RawType, resolved))
                count++;
        }
        return count > 0 && count <= 3;
    }

    private enum PointerStrategy
    {
        SafeSpan,
        SafeRef
    }

    private enum ReturnKind
    {
        Direct,
        Bool,
        Utf8String,
        StructPtr,
        VoidPtrAsNint
    }

    private static void EmitWrapperMethod(
        CSharpWriter writer,
        string nativeClass,
        string methodName,
        FunctionDefinition fn,
        LibraryDescriptor library,
        TypesInfo typesInfo,
        PointerStrategy strategy,
        bool omitNullBoolPtr,
        HashSet<string> emittedSignatures)
    {
        string nativeRetType = typesInfo.ResolveType(fn.RawReturnType, library);

        ReturnKind retKind;
        string wrapperRetType;
        if (IsBoolReturn(fn.RawReturnType))
        {
            retKind = ReturnKind.Bool;
            wrapperRetType = "bool";
        }
        else if (IsConstCharPtr(fn.RawReturnType))
        {
            retKind = ReturnKind.Utf8String;
            wrapperRetType = "string?";
        }
        else if (TryGetSingleStructPointerTarget(nativeRetType, library, typesInfo, out var retStruct))
        {
            retKind = ReturnKind.StructPtr;
            wrapperRetType = $"{retStruct}Ptr";
        }
        else if (IsVoidPtr(fn.RawReturnType, nativeRetType))
        {
            retKind = ReturnKind.VoidPtrAsNint;
            wrapperRetType = "nint";
        }
        else
        {
            retKind = ReturnKind.Direct;
            wrapperRetType = nativeRetType;
        }

        int n = fn.Parameters.Count;
        var paramInfos = new List<WrapperParam>(n);
        var usedNames = new HashSet<string>(StringComparer.Ordinal);

        for (int i = 0; i < n; i++)
        {
            var p = fn.Parameters[i];
            string nativeType = typesInfo.ResolveType(p.RawType, library);
            if (nativeType == "void") nativeType = "nint";

            string pName = IdentifierHelper.EscapeIdentifier(
                string.IsNullOrWhiteSpace(p.RawName) ? $"arg{i}" : p.RawName);
            while (!usedNames.Add(pName))
                pName += "_";

            bool hasDefault = fn.Defaults.TryGetValue(p.RawName, out var rawDefault);
            bool hasDefaultNull = hasDefault && (rawDefault == "NULL" || rawDefault == "nullptr" || rawDefault == "0");

            // Omit optional `bool* p_open = NULL` in the omitted overload
            if (omitNullBoolPtr && p.RawType.Trim() == "bool*" && hasDefaultNull)
            {
                paramInfos.Add(new WrapperParam(pName, nativeType, "", ParamKind.OmittedNull, null));
                continue;
            }

            ParamKind kind;
            string wrapperType;

            if (IsConstCharPtr(p.RawType))
            {
                kind = ParamKind.Utf8String;
                wrapperType = "string?";
            }
            else if (IsBoolParam(p.RawType))
            {
                kind = ParamKind.Bool;
                wrapperType = "bool";
            }
            else if (IsVoidPtr(p.RawType, nativeType))
            {
                kind = ParamKind.VoidPtrAsNint;
                wrapperType = "nint";
            }
            else if (strategy == PointerStrategy.SafeRef && IsRefFriendlyParam(p.RawType, nativeType))
            {
                if (p.RawType.Trim() == "bool*")
                {
                    kind = ParamKind.RefBool;
                    wrapperType = "ref bool";
                }
                else
                {
                    kind = ParamKind.RefValue;
                    string elemType = nativeType.Substring(0, nativeType.Length - 1);
                    wrapperType = $"ref {elemType}";
                }
            }
            else if (p.RawType.Trim() == "bool*")
            {
                // In SafeSpan mode, non-omitted bool* becomes Span<byte> (or ref bool if not default null)
                if (!hasDefaultNull)
                {
                    kind = ParamKind.RefBool;
                    wrapperType = "ref bool";
                }
                else
                {
                    kind = ParamKind.SpanBuffer;
                    wrapperType = "Span<byte>";
                }
            }
            else if (TryGetSpanElementType(nativeType, out var spanElem))
            {
                if (IsConstPointer(p.RawType))
                {
                    kind = ParamKind.ReadOnlySpanBuffer;
                    wrapperType = $"ReadOnlySpan<{spanElem}>";
                }
                else
                {
                    kind = ParamKind.SpanBuffer;
                    wrapperType = $"Span<{spanElem}>";
                }
            }
            else if (TryGetSingleStructPointerTarget(nativeType, library, typesInfo, out var paramStruct))
            {
                kind = ParamKind.StructPtr;
                wrapperType = $"{paramStruct}Ptr";
            }
            else if (hasDefault && rawDefault == $"{nativeType}()" && nativeType is "ImPlotSpec" or "ImPlot3DSpec")
            {
                kind = ParamKind.NullableDefaultStruct;
                wrapperType = $"{nativeType}?";
            }
            else
            {
                kind = ParamKind.Direct;
                wrapperType = nativeType;
            }

            string? csharpDefault = null;
            if (hasDefault && kind != ParamKind.RefBool && kind != ParamKind.RefValue)
            {
                csharpDefault = TryTranslateDefault(rawDefault!, wrapperType, kind, library, typesInfo);
            }

            paramInfos.Add(new WrapperParam(pName, nativeType, wrapperType, kind, csharpDefault));
        }

        // Enforce C# rule: only contiguous trailing visible parameters can have default values
        bool allowDefault = true;
        for (int i = paramInfos.Count - 1; i >= 0; i--)
        {
            if (paramInfos[i].Kind == ParamKind.OmittedNull)
                continue;

            if (allowDefault && paramInfos[i].DefaultValue != null)
            {
                paramInfos[i].UseDefault = true;
            }
            else
            {
                allowDefault = false;
                paramInfos[i].UseDefault = false;
            }
        }

        var visibleParams = paramInfos.Where(p => p.Kind != ParamKind.OmittedNull).ToList();

        // Deduplicate by C# method signature (name + parameter types/modifiers)
        var sigKey = new StringBuilder(methodName);
        sigKey.Append('(');
        for (int i = 0; i < visibleParams.Count; i++)
        {
            if (i > 0) sigKey.Append(',');
            sigKey.Append(visibleParams[i].WrapperType);
        }
        sigKey.Append(')');

        if (!emittedSignatures.Add(sigKey.ToString()))
            return;

        // Only mark method `unsafe` if its signature itself contains a raw pointer
        bool signatureRequiresUnsafe = wrapperRetType.Contains("*") || visibleParams.Any(p => p.WrapperType.Contains("*"));
        string unsafeModifier = signatureRequiresUnsafe ? "unsafe " : "";

        var decls = visibleParams.Select(p =>
            p.UseDefault ? $"{p.WrapperType} {p.Name} = {p.DefaultValue}" : $"{p.WrapperType} {p.Name}");

        writer.WriteLineIndented($"public static {unsafeModifier}{wrapperRetType} {methodName}({string.Join(", ", decls)})");
        using (writer.WriteBlock())
        {
            if (!signatureRequiresUnsafe)
            {
                writer.WriteLineIndented("unsafe");
                using (writer.WriteBlock())
                {
                    EmitWrapperBody(writer, nativeClass, fn.EntryPoint, paramInfos, wrapperRetType, retKind);
                }
            }
            else
            {
                EmitWrapperBody(writer, nativeClass, fn.EntryPoint, paramInfos, wrapperRetType, retKind);
            }
        }
        writer.WriteLine();
    }

    private static void EmitWrapperBody(
        CSharpWriter writer,
        string nativeClass,
        string entryPoint,
        List<WrapperParam> paramInfos,
        string wrapperRetType,
        ReturnKind retKind)
    {
        var callArgs = new List<string>(paramInfos.Count);
        var refBoolFixups = new List<(string ParamName, string LocalName)>();
        var fixedStatements = new List<string>();
        int utf8Idx = 0;

        foreach (var p in paramInfos)
        {
            switch (p.Kind)
            {
                case ParamKind.OmittedNull:
                    callArgs.Add("null");
                    break;
                case ParamKind.Utf8String:
                {
                    string bufName = $"__buf{utf8Idx}";
                    string strName = $"__utf8_{utf8Idx}";
                    utf8Idx++;
                    writer.WriteLineIndented($"Span<byte> {bufName} = stackalloc byte[256];");
                    writer.WriteLineIndented($"using var {strName} = new ScopedUtf8String({p.Name}, {bufName});");
                    callArgs.Add($"{strName}.Pointer");
                    break;
                }
                case ParamKind.Bool:
                    callArgs.Add($"{p.Name} ? (byte)1 : (byte)0");
                    break;
                case ParamKind.VoidPtrAsNint:
                    callArgs.Add($"(void*){p.Name}");
                    break;
                case ParamKind.StructPtr:
                    callArgs.Add($"{p.Name}.NativePtr");
                    break;
                case ParamKind.NullableDefaultStruct:
                    callArgs.Add($"{p.Name} ?? {p.NativeType}.Default");
                    break;
                case ParamKind.RefBool:
                {
                    string local = $"__b_{p.Name.TrimStart('@')}";
                    writer.WriteLineIndented($"byte {local} = {p.Name} ? (byte)1 : (byte)0;");
                    callArgs.Add($"&{local}");
                    refBoolFixups.Add((p.Name, local));
                    break;
                }
                case ParamKind.RefValue:
                {
                    string ptrName = $"__p_{p.Name.TrimStart('@')}";
                    fixedStatements.Add($"fixed ({p.NativeType} {ptrName} = &{p.Name})");
                    callArgs.Add(ptrName);
                    break;
                }
                case ParamKind.SpanBuffer:
                case ParamKind.ReadOnlySpanBuffer:
                {
                    string ptrName = $"__s_{p.Name.TrimStart('@')}";
                    fixedStatements.Add($"fixed ({p.NativeType} {ptrName} = {p.Name})");
                    callArgs.Add(ptrName);
                    break;
                }
                default:
                    callArgs.Add(p.Name);
                    break;
            }
        }

        foreach (var fixedStmt in fixedStatements)
        {
            writer.WriteLineIndented(fixedStmt);
        }

        if (fixedStatements.Count > 0)
        {
            using (writer.WriteBlock())
            {
                EmitNativeCall(writer, nativeClass, entryPoint, callArgs, wrapperRetType, retKind, refBoolFixups);
            }
        }
        else
        {
            EmitNativeCall(writer, nativeClass, entryPoint, callArgs, wrapperRetType, retKind, refBoolFixups);
        }
    }

    private static void EmitNativeCall(
        CSharpWriter writer,
        string nativeClass,
        string entryPoint,
        List<string> callArgs,
        string wrapperRetType,
        ReturnKind retKind,
        List<(string ParamName, string LocalName)> refBoolFixups)
    {
        string callExpr = $"{nativeClass}.{entryPoint}({string.Join(", ", callArgs)})";

        if (wrapperRetType == "void")
        {
            writer.WriteLineIndented($"{callExpr};");
            foreach (var (paramName, localName) in refBoolFixups)
                writer.WriteLineIndented($"{paramName} = {localName} != 0;");
        }
        else if (refBoolFixups.Count > 0)
        {
            writer.WriteLineIndented($"var __ret = {callExpr};");
            foreach (var (paramName, localName) in refBoolFixups)
                writer.WriteLineIndented($"{paramName} = {localName} != 0;");

            writer.WriteLineIndented($"return {FormatReturn("__ret", retKind, wrapperRetType)};");
        }
        else
        {
            writer.WriteLineIndented($"return {FormatReturn(callExpr, retKind, wrapperRetType)};");
        }
    }

    private static string FormatReturn(string expr, ReturnKind retKind, string wrapperRetType) => retKind switch
    {
        ReturnKind.Bool => $"{expr} != 0",
        ReturnKind.Utf8String => $"Utf8StringHelper.PtrToStringUtf8({expr})",
        ReturnKind.StructPtr => $"new {wrapperRetType}({expr})",
        ReturnKind.VoidPtrAsNint => $"(nint)({expr})",
        _ => expr
    };

    private static string? TryTranslateDefault(string rawDefault, string wrapperType, ParamKind kind, LibraryDescriptor library, TypesInfo typesInfo)
    {
        string d = rawDefault.Trim();

        if (kind == ParamKind.NullableDefaultStruct)
        {
            return "null";
        }

        if (kind is ParamKind.StructPtr or ParamKind.SpanBuffer or ParamKind.ReadOnlySpanBuffer)
        {
            return (d == "NULL" || d == "nullptr" || d == "0") ? "default" : null;
        }

        if (wrapperType == "string?")
        {
            if (d == "NULL" || d == "nullptr" || d == "0")
                return "null";
            if (d.StartsWith("\"", StringComparison.Ordinal) && d.EndsWith("\"", StringComparison.Ordinal))
                return d;
            return null;
        }

        if (wrapperType.EndsWith("*", StringComparison.Ordinal))
        {
            return (d == "NULL" || d == "nullptr" || d == "0") ? "null" : null;
        }

        if (wrapperType == "nint" || wrapperType == "nuint")
        {
            if (d == "NULL" || d == "nullptr" || d == "0")
                return "0";
            return null;
        }

        if (wrapperType == "bool")
        {
            if (d == "true" || d == "1") return "true";
            if (d == "false" || d == "0") return "false";
            return null;
        }

        if (wrapperType == "float")
        {
            if (d == "FLT_MAX") return "float.MaxValue";
            if (d == "-FLT_MAX") return "-float.MaxValue";
            if (d == "FLT_MIN") return "float.Epsilon";
            if (d == "-FLT_MIN") return "-float.Epsilon";
            if (FloatLiteralRegex.IsMatch(d))
                return d.EndsWith("f", StringComparison.OrdinalIgnoreCase) ? d : d + "f";
            return null;
        }

        if (wrapperType == "double")
        {
            if (d == "DBL_MAX") return "double.MaxValue";
            if (d == "-DBL_MAX") return "-double.MaxValue";
            if (FloatLiteralRegex.IsMatch(d))
                return d.TrimEnd('f', 'F');
            return null;
        }

        if (wrapperType is "int" or "uint" or "short" or "ushort" or "byte" or "sbyte" or "long" or "ulong")
        {
            if (d == "IMPLOT_AUTO" || d == "IMPLOT_AUTO_COL")
                return null;
            if (IntLiteralRegex.IsMatch(d))
            {
                string clean = d.TrimEnd('u', 'U', 'l', 'L');
                return wrapperType is "uint" or "ulong" ? clean + "u" : clean;
            }
            return null;
        }

        if (typesInfo.IsEnum(wrapperType, library))
        {
            if (d == "0")
                return $"({wrapperType})0";
            if (IntLiteralRegex.IsMatch(d))
                return $"({wrapperType})({d.TrimEnd('u', 'U', 'l', 'L')})";

            string enumPrefix = wrapperType + "_";
            var parts = d.Split(['|'], StringSplitOptions.RemoveEmptyEntries);
            var translatedParts = new List<string>(parts.Length);
            bool allValid = parts.Length > 0;
            foreach (var rawPart in parts)
            {
                string part = rawPart.Trim();
                if (part.StartsWith(enumPrefix, StringComparison.Ordinal))
                {
                    string member = IdentifierHelper.EscapeIdentifier(part.Substring(enumPrefix.Length));
                    translatedParts.Add($"{wrapperType}.{member}");
                }
                else
                {
                    allValid = false;
                    break;
                }
            }
            if (allValid)
                return string.Join(" | ", translatedParts);

            return null;
        }

        if (ZeroVecRegex.IsMatch(d))
        {
            return "default";
        }

        if (d == $"{wrapperType}()" && typesInfo.IsStruct(wrapperType, library))
        {
            return "default";
        }

        return null;
    }

    private enum ParamKind
    {
        Direct,
        OmittedNull,
        Utf8String,
        Bool,
        VoidPtrAsNint,
        StructPtr,
        NullableDefaultStruct,
        RefBool,
        RefValue,
        SpanBuffer,
        ReadOnlySpanBuffer
    }

    private class WrapperParam
    {
        public string Name { get; }
        public string NativeType { get; }
        public string WrapperType { get; }
        public ParamKind Kind { get; }
        public string? DefaultValue { get; }
        public bool UseDefault { get; set; }

        public WrapperParam(string name, string nativeType, string wrapperType, ParamKind kind, string? defaultValue)
        {
            Name = name;
            NativeType = nativeType;
            WrapperType = wrapperType;
            Kind = kind;
            DefaultValue = defaultValue;
        }
    }
