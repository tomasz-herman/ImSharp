internal class FunctionDefinition
{
    public string EntryPoint { get; }
    public string FuncName { get; }
    public string StructName { get; }
    public string Namespace { get; }
    public string Location { get; }
    public LibraryDescriptor Library { get; }
    public string RawReturnType { get; }
    public bool IsConstructor { get; }
    public bool IsDestructor { get; }
    public bool IsTemplated { get; }
    public bool IsSkipped { get; }
    public bool IsVarArg { get; }
    public List<FunctionParameter> Parameters { get; } = [];
    public Dictionary<string, string> Defaults { get; } = new();

    public bool IsInternal =>
        Location.IndexOf("internal", StringComparison.OrdinalIgnoreCase) >= 0;

    public bool IsFreeType =>
        Location.IndexOf("freetype", StringComparison.OrdinalIgnoreCase) >= 0;

    public bool HasCppStdType =>
        RawReturnType.Contains("std::") || Parameters.Any(p => p.RawType.Contains("std::"));

    public bool ShouldSkipNative =>
        IsTemplated || IsSkipped || IsFreeType || IsVarArg || HasCppStdType || string.IsNullOrEmpty(EntryPoint);

    public FunctionDefinition(JObject ov, LibraryDescriptor library)
    {
        Library = library;
        EntryPoint = ov["ov_cimguiname"]?.ToString() ?? ov["cimguiname"]?.ToString() ?? "";
        FuncName = ov["funcname"]?.ToString() ?? "";
        StructName = ov["stname"]?.ToString() ?? "";
        Namespace = ov["namespace"]?.ToString() ?? "";
        Location = ov["location"]?.ToString() ?? "";
        IsConstructor = ov["constructor"]?.ToObject<bool>() ?? false;
        IsDestructor = ov["destructor"]?.ToObject<bool>() ?? false;
        IsTemplated = ov["templated"]?.ToObject<bool>() ?? false;
        IsSkipped = ov["skipped"]?.ToObject<bool>() ?? false;
        IsVarArg = !string.IsNullOrEmpty(ov["isvararg"]?.ToString());

        string? ret = ov["ret"]?.ToString();
        if (string.IsNullOrEmpty(ret))
        {
            ret = IsConstructor && !string.IsNullOrEmpty(StructName) ? StructName + "*" : "void";
        }
        RawReturnType = ret!;

        if (ov["defaults"] is JObject defaultsObj)
        {
            foreach (var kv in defaultsObj)
            {
                if (kv.Value != null)
                    Defaults[kv.Key] = kv.Value.ToString();
            }
        }

        if (ov["argsT"] is JArray argsArr)
        {
            foreach (var arg in argsArr)
            {
                string argName = arg["name"]?.ToString() ?? "";
                string argType = arg["type"]?.ToString() ?? "";
                if (argType == "..." || argName == "...")
                {
                    IsVarArg = true;
                    continue;
                }
                if (!string.IsNullOrEmpty(argType))
                {
                    Parameters.Add(new FunctionParameter(argName, argType));
                }
            }
        }
    }

    public class FunctionParameter
    {
        public string RawName { get; }
        public string RawType { get; }

        public FunctionParameter(string rawName, string rawType)
        {
            RawName = rawName;
            RawType = rawType;
        }
    }
}

